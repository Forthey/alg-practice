#include <gtest/gtest.h>

#include "solution.h"

namespace {
struct TestCase {
    std::vector<int> nums;
    std::size_t l;
    std::size_t r;
    std::vector<int> expected;
};

void PrintTo(const TestCase& p, std::ostream* os) {
    *os << "{ nums = {";

    for (std::size_t i = 0; i < p.nums.size(); ++i) {
        if (i != 0) {
            *os << ", ";
        }
        *os << p.nums[i];
    }

    *os << "}, l = " << p.l << ", r = " << p.r << ", expected = {";

    for (std::size_t i = 0; i < p.expected.size(); ++i) {
        if (i != 0) {
            *os << ", ";
        }
        *os << p.expected[i];
    }

    *os << "} }";
}

TestCase testCases[] = {
    // Минимальный массив.
    {{5}, 1, 1, {5}},
    // Длина подотрезка фиксирована.
    {{1, 2, 3, 4}, 2, 2, {3, 4}},
    // Все числа отрицательные, можно взять один элемент.
    {{-8, -3, -6, -2, -5, -4}, 1, 3, {-2}},
    // Все числа отрицательные, но нужно взять хотя бы два.
    {{-8, -3, -6, -2, -5, -4}, 2, 3, {-2, -5}},
    // Оптимальная длина находится строго между L и R.
    {{-2, 5, -1, 4, -10, 3}, 2, 4, {5, -1, 4}},
    // Оптимальный подотрезок начинается с первого элемента.
    {{7, 2, -10, 1, 1}, 2, 3, {7, 2}},
    // Оптимальный подотрезок заканчивается последним элементом.
    {{-10, 1, 1, 6, 5}, 2, 3, {1, 6, 5}},
    // L = R = n: можно выбрать только весь массив.
    {{3, -2, 5, -1}, 4, 4, {3, -2, 5, -1}},
    // R = n, но весь массив брать невыгодно.
    {{4, -100, 5, 6}, 1, 4, {5, 6}},
    // Оптимальная длина равна L.
    {{-10, 8, 7, -20, 6}, 2, 4, {8, 7}},
    // Оптимальная длина равна R.
    {{-20, 4, 5, 6, -20}, 1, 3, {4, 5, 6}},
    // Большой отрицательный элемент разделяет две хорошие области.
    {{2, 3, -100, 10, 11, -5}, 2, 3, {10, 11}},
    // Положительные и отрицательные элементы чередуются.
    {{5, -2, 6, -20, 4, -1}, 2, 3, {5, -2, 6}},
    // Нули рядом с оптимальным участком.
    // Ограничение на длину делает ответ однозначным.
    {{0, -10, 0, 7, 0, -10}, 3, 3, {0, 7, 0}},
    // Все элементы положительные: выгодно взять максимально
    // разрешенную длину.
    {{1, 2, 3, 4, 5}, 2, 4, {2, 3, 4, 5}},
    // L = 1, R = 1: фактически ищем максимальный элемент.
    {{-5, 3, 10, 2, 1}, 1, 1, {10}},
};
class SolutionTest : public ::testing::TestWithParam<TestCase> {
protected:
};

TEST_P(SolutionTest, ReturnsExpected) {
    const auto& param = GetParam();

    EXPECT_EQ(param.expected, findMaxSubSegment(param.nums, param.l, param.r));
}

INSTANTIATE_TEST_SUITE_P(SolutionTest, SolutionTest, testing::ValuesIn(testCases));
}  // namespace
